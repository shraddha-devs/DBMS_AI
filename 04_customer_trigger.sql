-- Practical 4: SQLite row-level triggers and a persistent audit table.
-- SQLite trigger pseudo-columns use OLD.column / NEW.column (no colons).

CREATE TABLE IF NOT EXISTS CUSTOMERS (
    ID      INTEGER PRIMARY KEY,
    NAME    TEXT NOT NULL,
    AGE     INTEGER,
    ADDRESS TEXT,
    SALARY  REAL
);

CREATE TABLE IF NOT EXISTS CUSTOMERS_AUDIT (
    AUDIT_ID          INTEGER PRIMARY KEY AUTOINCREMENT,
    CUSTOMER_ID       INTEGER NOT NULL,
    ACTION            TEXT NOT NULL CHECK (ACTION IN ('INSERT', 'UPDATE', 'DELETE')),
    OLD_SALARY        REAL,
    NEW_SALARY        REAL,
    SALARY_DIFFERENCE REAL,
    CHANGED_AT        TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Q4(a): INSERT and DELETE have one unavailable salary image; UPDATE records
-- NEW.SALARY - OLD.SALARY. These are SQLite row-level triggers.
CREATE TRIGGER IF NOT EXISTS CUSTOMERS_AUDIT_INSERT
AFTER INSERT ON CUSTOMERS
BEGIN
    INSERT INTO CUSTOMERS_AUDIT
        (CUSTOMER_ID, ACTION, OLD_SALARY, NEW_SALARY, SALARY_DIFFERENCE)
    VALUES (NEW.ID, 'INSERT', NULL, NEW.SALARY, NULL);
END;

CREATE TRIGGER IF NOT EXISTS CUSTOMERS_AUDIT_UPDATE
AFTER UPDATE ON CUSTOMERS
BEGIN
    INSERT INTO CUSTOMERS_AUDIT
        (CUSTOMER_ID, ACTION, OLD_SALARY, NEW_SALARY, SALARY_DIFFERENCE)
    VALUES (
        NEW.ID,
        'UPDATE',
        OLD.SALARY,
        NEW.SALARY,
        NEW.SALARY - OLD.SALARY
    );
END;

CREATE TRIGGER IF NOT EXISTS CUSTOMERS_AUDIT_DELETE
AFTER DELETE ON CUSTOMERS
BEGIN
    INSERT INTO CUSTOMERS_AUDIT
        (CUSTOMER_ID, ACTION, OLD_SALARY, NEW_SALARY, SALARY_DIFFERENCE)
    VALUES (OLD.ID, 'DELETE', OLD.SALARY, NULL, NULL);
END;

-- Q4(b): Exercise all three triggers. The generated ID is one above the
-- current maximum; the test customer is deleted while its audit records stay.
INSERT INTO CUSTOMERS (ID, NAME, AGE, ADDRESS, SALARY)
SELECT COALESCE(MAX(ID), 0) + 1,
       'Practical 4 Trigger Test', 30, '1 Test Street', 50000
FROM CUSTOMERS;

UPDATE CUSTOMERS
SET SALARY = 57500
WHERE ID = (SELECT MAX(ID) FROM CUSTOMERS);

DELETE FROM CUSTOMERS
WHERE ID = (SELECT MAX(ID) FROM CUSTOMERS);

-- Verification: latest three audit entries should be INSERT, UPDATE (+7500),
-- and DELETE; the temporary customer row should not remain.
SELECT AUDIT_ID, CUSTOMER_ID, ACTION, OLD_SALARY, NEW_SALARY, SALARY_DIFFERENCE
FROM CUSTOMERS_AUDIT
ORDER BY AUDIT_ID DESC
LIMIT 3;
SELECT COUNT(*) AS TRIGGER_TEST_CUSTOMERS_REMAINING
FROM CUSTOMERS
WHERE NAME = 'Practical 4 Trigger Test';
